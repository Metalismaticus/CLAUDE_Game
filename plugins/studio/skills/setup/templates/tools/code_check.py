def git(root, *args, check=False):
    """Вызов git в папке проекта; текст вывода или None при ошибке."""
    try:
        run = subprocess.run(["git", "-c", "core.quotepath=off", "-C", root] + list(args), capture_output=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return None if run.returncode != 0 and check else run.stdout.decode("utf-8", "replace")


def norm(line):
    return " ".join(line.split())


def digest(text):
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:12]


