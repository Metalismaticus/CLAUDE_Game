def check_rules(model, rev, new, rep):
    """Н8 — ослаблены типы против rev; Н9 — новая служба [autoload] без записи в «Архитектуре».

    @warning_ignore тех ключей, которые этот же diff поднял, — не ослабление: так включают по папкам.
    Н9 с --changed — заметка: CONCEPT.md исполнителю не править, запись вносит /done из его строки
    `CONCEPT, Службы` (её сверяет проверяющий).
    """
    root, fix, raised = model.root, "вернуть как было — типы не ослаблять", set()
    old_ini = shown(root, rev, "project.godot")
    if old_ini is not None:
        now, was = warn_levels(model.godot), warn_levels(old_ini)
        raised = {key for key, level in now.items() if level > was.get(key, 0)}
        for key, level in was.items():
            if now.get(key, 0) < level:
                rep.add(True, 1, "project.godot", None, f"ослаблены типы: gdscript/warnings/{key} {level} → "
                        f"{now.get(key, 0)}", fix)
        names = set(re.findall(r"(?m)^(\w+)\s*=", section(model.godot, "autoload")))
        arch = architecture(root)
        for name in sorted(names - set(re.findall(r"(?m)^(\w+)\s*=", section(old_ini, "autoload")))):
            if not re.search(r"\b" + re.escape(name) + r"\b", arch):
                rep.add(new is None, 1, "project.godot", None, f"служба {name} без записи в «Архитектуре» docs/CONCEPT"
                        ".md", "строкой в «Архитектуру» или узлом сцены" if new is None else
                        f"в итоге, в «В документы при /done» — `CONCEPT, Службы: {name} — <что хранит>`")
    for path in (p for p in model.paths if p.endswith(".csproj")):
        old, now = shown(root, rev, path) or "", "\n".join(read_lines(os.path.join(root, path)) or [])
        for tag, value in (("Nullable", "enable"), ("TreatWarningsAsErrors", "true")):
            if re.search(rf"<{tag}>\s*{value}\s*<", old, re.I) and not re.search(rf"<{tag}>\s*{value}\s*<", now, re.I):
                rep.add(True, 1, path, None, f"ослаблены типы: <{tag}> больше не {value}", fix)
    for path, lines in (new or {}).items():
        src = model.sources[path]
        for i in sorted(lines):  # директива C# и аннотация GDScript — не в строках и комментариях
            if src.lang == "cs" and re.match(r"\s*#nullable\s+disable\b", src.code[i]) or src.lang == "gd" and \
                    IGNORE_TYPES.search(src.text[i]) and not set(re.findall(r"untyped_declaration|unsafe_\w+",
                                                                            src.text[i])) <= raised:
                rep.add(True, 1, path, i, f"ослаблены типы: {src.raw[i].strip()[:60]}", fix)


def check_raised(model, rev, rel, base, rep, joined):
    """Н10 — база выше, чем в rev: итог счётчиков, новая запись (кроме перенесённой), порог, exclude.

    Новые разделы — от --add-new-metrics — не в счёт; запись под новым ключом — не подъём, если ушла
    запись не меньше (у файла — которого больше нет, у функции — с тем же отпечатком или именем), а у
    повтора (новый ключ или больше мест) — если joined(ключ): повтор из базы, задетый с rev (joined_repeats; без
    --changed rev — HEAD, и такой повтор в незакоммиченной базе — только от --tighten).
    """
    old = as_base(shown(model.root, rev, rel)) if rel else None
    if old is None:
        return
    fix, rule = "базу поднимать нельзя — вернуть числа", "только пунктом очереди о порогах, с причиной — назвать в итоге"
    for sec in (s for s in SECTIONS if s in old):
        now_sec, was_sec = base.get(sec, {}), old[sec]
        if sec in COUNTERS:  # счётчики — итогом: перенос между файлами не подъём
            now_sec, was_sec = {"итог": sum(now_sec.values())}, {"итог": sum(was_sec.values())}
        credit = {k: v for k, v in was_sec.items() if k not in now_sec and (sec == "functions" or sec == "files"
                                                                             and k not in model.sources)}
        for key, value in now_sec.items():
            now, was = number(value), number(was_sec.get(key))
            moved = was is None and next((k for k, v in credit.items() if number(v) >= now and (
                sec == "files" or v[1] == value[1] or k.split("::", 1)[1] == key.split("::", 1)[1])), None)
            if moved:
                del credit[moved]
            elif (was is None or now > was) and not (sec == "repeats" and joined(key)):
                rep.add(True, 1, rel, None, f"база поднята: {sec} «{key}» {was if was is not None else 'нет'} → {now}",
                        fix)
    for key, value in base.get("limits", {}).items():
        if value > old.get("limits", {}).get(key, LIMITS.get(key, (value,))[0]):
            rep.add(True, 1, rel, None, f"база поднята: порог {key} до {value}", rule)
    for item in sorted(set(base.get("exclude", [])) - set(old.get("exclude", []))):
        rep.add(True, 1, rel, None, f"база поднята: из замера исключено {item}", rule)


def note_classes(model, lim, new, rep):
    """Класс с множеством полей или открытых методов; с --changed — только перешедший порог этим diff."""
    for path, src in model.code():
        for cls in src.classes:
            grown = sum(1 for i in cls["decl"] if i in new.get(path, ())) if new is not None else 0
            if new is not None and (not grown or cls["fields"] - grown > lim["class_fields"]
                                    or cls["methods"] - grown > lim["class_methods"]):
                continue
            if cls["fields"] > lim["class_fields"] or cls["methods"] > lim["class_methods"]:
                rep.add(False, max(cls["fields"] / lim["class_fields"], cls["methods"] / lim["class_methods"]),
                        path, cls["start"], f"класс {cls['name']}: полей {cls['fields']}, открытых методов "
                        f"{cls['methods']} (заметка от {lim['class_fields']} и {lim['class_methods']})",
                        "запись или часть — своим типом")


def note_numbers(model, new, rep):
    """Одинаковый набор из двух и больше дробных чисел в двух файлах (0, 1, 0.5, 2 не в счёт)."""
    sets = defaultdict(list)
    for path, src in model.sources.items():
        for i, code in enumerate(src.code):
            values = [v for v in FLOAT.findall(code) if float(v) not in (0.0, 1.0, 0.5, 2.0)]
            if len(set(float(v) for v in values)) > 1:  # (10.0, 10.0) — одно число, не набор
                sets[tuple(float(v) for v in values)].append((path, i, values))
    for spots in sets.values():
        files = sorted(set(s[0] for s in spots))
        fresh = [s for s in spots if new is not None and s[1] in new.get(s[0], ())]
        if len(files) > 1 and (new is None or fresh):
            path, line, values = (fresh or spots)[0]
            other = next(f"{p}:{i + 1}" for p, i, _ in spots if p != path)
            rep.add(False, len(files) / 2, path, line, f"набор чисел ({', '.join(values[:4])}{' …' * (len(values) > 4)})"
                    f" ещё в {other} (файлов {len(files)})", "одно определение с именем, остальные берут его")


def declarations(model):
    """Объявления, которые ищутся по тексту проекта: (файл, строка, имя, открытое)."""
    found = []
    for path, src in model.code():
        if src.lang == "gd":
            found += [(path, f["start"], f["name"], f["public"]) for f in src.funcs]
            found += [(path, i, m.group(1), True) for i, c in enumerate(src.code)
                      for m in [re.match(r"(?:static\s+)?const\s+(\w+)", c)] if m]
        elif src.lang == "cs" and not re.search(r"\bclass\s+\w+[^{]*:[^{]*\bI[A-Z]\w*", "\n".join(src.code)):
            for i, code in enumerate(src.code):
                found += [(path, i, m.group(1), True) for m in PUBLIC_CS.finditer(code)]
                const = re.search(r"\b(?:const|static\s+readonly)\s+[\w<>\[\],.?]+\s+(\w+)\s*=", code)
                found += [(path, i, const.group(1), "public" in code)] if const else []
        elif src.lang in ("py", "js"):
            rx = r"(?:async\s+)?def\s+(\w+)|([A-Z][A-Z0-9_]+)\s*=" if src.lang == "py" else \
                r"(?:export\s+)?(?:async\s+)?function\s*\*?\s*(\w+)"
            found += [(path, i, m.group(1) or m.group(m.lastindex), not m.group(m.lastindex).startswith("_"))
                      for i, c in enumerate(src.code) for m in [re.match(rx, c)] if m]
    return [d for d in found if d[2] not in VIRTUALS and not d[2].startswith(("_on_", "test", "_test", "__"))
            and d[2] != "main"]


def note_dead(model, new, rep):
    """Мёртвое: имени больше нигде в тексте проекта нет; открытое, которое зовут только проверки.

    Файл зовёт по собранному имени (call("_" + layer)) — его имена с этой приставкой не мёртвые.
    """
    decls = declarations(model)
    total = Counter(d[2] for d in decls)
    outside = Counter(d[2] for d in decls if not is_test(d[0]))
    built = {p: re.findall(r"""(?:\b(?:call|callv|call_deferred|has_method)\(|Callable\([^,()]*,)\s*&?["'](\w*)"""
                           r"""[^"'\n]*["']\s*[+%]""", "\n".join(src.text)) for p, src in model.code()}
    for path, line, name, public in decls:
        if new is not None and line not in new.get(path, ()) or any(name.startswith(b) for b in built.get(path, ())):
            continue
        if model.ids[name] <= total[name]:
            rep.add(False, 1, path, line, f"мёртвое: {name} — больше нигде не упоминается", "удалить")
        elif public and not is_test(path) and model.test_ids[name] and \
                model.ids[name] - model.test_ids[name] <= outside[name]:
            rep.add(False, 0.5, path, line, f"{name} зовут только проверки", "удалить или подключить")


def note_design(model, new, rep):
    """Переусложнение: базовый класс с одним наследником, class_name с одной ссылкой."""
    heirs, declared = Counter(), {}
    for path, src in model.code():
        for i, code in enumerate(src.code):
            named = re.match(r"\s*class_name\s+(\w+)", code) if src.lang == "gd" else re.search(
                r"\bclass\s+(\w+)(?:\s*<[^>]*>)?\s*(?:\(\s*(\w+)|:\s*(\w+)|\s+extends\s+(\w+))?", code)
            if named:
                declared[named.group(1)] = (path, i, src.lang)
                heirs.update(g for g in named.groups()[1:] if g)
            parent = re.match(r"\s*(?:class\s+\w+\s+)?extends\s+(\w+)", code) if src.lang == "gd" else None
            heirs.update([parent.group(1)] if parent else [])
    for name, (path, line, lang) in declared.items():
        if new is not None and line not in new.get(path, ()):
            continue
        if heirs[name] == 1:
            rep.add(False, 0.5, path, line, f"базовый класс {name} с одним наследником", "слить с наследником")
        elif lang == "gd" and model.ids[name] <= 2:
            rep.add(False, 0.3, path, line, f"class_name {name}: ссылок {max(0, model.ids[name] - 1)}", "убрать class_name")


def note_lines(model, lim, new, rep):
    """По строкам: Dictionary без типов, обращение вверх по дереву, ссылки на пункты очереди, комментарии."""
    autoload = {p.split("res://", 1)[-1] for p in re.findall(r'"\*?(res://[^"]+)"', section(model.godot, "autoload"))}
    rules = (("untyped_dict", "Dictionary без типов", "запись — классом, коллекция — Dictionary[K, V]"),
             ("uptree", "обращение вверх по дереву", "сигнал или ссылка от родителя"),
             ("queue", "ссылки на пункты очереди", "ссылку — на постоянный документ, историю — в DECISIONS.md"))
    for path, src in model.code():
        godot_dict = src.lang == "cs" and any(line.strip() == "using Godot.Collections;" for line in src.raw)
        hits = defaultdict(list)
        for i, text in enumerate(src.text):
            if new is not None and i not in new.get(path, ()):
                continue
            if src.lang == "gd" and re.search(r"->\s*Dictionary\s*:", src.code[i]) or src.lang == "cs" and (
                    "public" not in text and ("Godot.Collections.Dictionary" in text
                                              or godot_dict and re.search(r"\bDictionary\b(?!\s*<)", text))):
                hits["untyped_dict"].append(i)
            if src.lang in ("gd", "cs") and (UPTREE.search(text) or path not in autoload and re.search(r"[\"']/root/", text)):
                hits["uptree"].append(i)
            if QUEUE_REF.search(src.raw[i]) and not QUEUE_REF.search(text):  # в комментарии, не в строке
                hits["queue"].append(i)
        for key, what, fix in rules:
            if hits[key]:
                rep.add(False, len(hits[key]) / 20, path, hits[key][0], f"{what}: {len(hits[key])}", fix)
        share = sum(src.note) * 100 // max(1, sum(src.note) + src.size)
        if new is None and src.size >= 50 and share > lim["comment_share"]:
            rep.add(False, 0.2, path, None, f"комментарии — {share}% строк (заметка — больше {lim['comment_share']}%)",
                    "историю — в git и DECISIONS.md, в коде — почему сейчас так")


