class Source:
    """Один файл: строки без комментариев, значимые строки, функции и классы."""

    def __init__(self, path, raw, lang):
        self.path, self.raw, self.lang, self.funcs, self.classes = path, raw, lang, [], []
        scan(self)
        self.size = sum(self.sig)
        {"gd": scopes_indent, "py": scopes_indent, "cs": scopes_brace, "js": scopes_brace}.get(lang, lambda _: None)(self)
        seen = Counter()
        for func in sorted(self.funcs, key=lambda f: f["start"]):  # перегрузки C# — разные ключи базы
            seen[func["qual"]] += 1
            func["qual"] += f"#{seen[func['qual']]}" if seen[func["qual"]] > 1 else ""

    def body(self, start, end):
        return [norm(self.text[i]) for i in range(start, end + 1) if self.sig[i]]


def scan(src):
    """text — без комментариев, литералы на месте; code — литералы пусты; sig, note, depth, cont по строкам."""
    hashy = src.lang in ("gd", "py")
    special = re.compile(r"[\"'#]" if hashy else r"[\"'`/]")
    src.text, src.code, src.sig, src.note, src.depth, src.cont = [], [], [], [], [], []
    state, depth = None, 0
    for line in src.raw:
        src.depth.append(depth)
        src.cont.append(state is not None)
        commented = state == "/*" or (state is not None and state[2])
        if state is None and not special.search(line):
            text = code = line
            depth = max(0, depth + sum(line.count(c) for c in "([{") - sum(line.count(c) for c in ")]}"))
        else:
            text, code, state, depth, hit = scan_line(line, state, depth, hashy, src.lang == "js")
            commented = commented or hit
        src.text.append(text)
        src.code.append(code)
        src.sig.append(bool(text.strip()))
        src.note.append(not text.strip() and commented and bool(line.strip()))
    src.depth.append(depth)
    src.cont.append(state is not None)


def scan_line(line, state, depth, hashy, js):
    """Одна строка посимвольно: строки-литералы, комментарии, скобки.

    tail — последние значимые знаки кода: по ним «/» в JS — начало регулярного выражения, а не деление
    (без склейки всей строки на каждом знаке — длинная строка разбиралась бы квадратично).
    """
    text, code, i, n, hit, tail = [], [], 0, len(line), False, ""
    while i < n:
        if state == "/*":
            j = line.find("*/", i)
            i, state = (n, state) if j < 0 else (j + 2, None)
            continue
        if state:
            quote, esc, doc = state
            j = i
            while j < n and not line.startswith(quote, j):
                j += 2 if esc and line[j] == "\\" else 1
            if not doc:
                text.append(line[i:j])
            if j >= n:
                state = None if len(quote) == 1 and quote != "`" and esc else state
                break
            if not esc and quote == '"' and line.startswith('""', j):
                text.append('""') if not doc else None
                i = j + 2
                continue
            if not doc:
                text.append(quote)
                code.append(quote)
                tail += quote
            i, state = j + len(quote), None
            continue
        ch = line[i]
        if (hashy and ch == "#") or (not hashy and line.startswith("//", i)):
            hit = True
            break
        if not hashy and line.startswith("/*", i):
            state, hit, i = "/*", True, i + 2
            continue
        if ch in "\"'`":
            quote = ch * 3 if hashy and line.startswith(ch * 3, i) else ch
            esc = not (not hashy and ch == '"' and line[max(0, i - 2):i].count("@"))
            doc = hashy and len(quote) == 3 and depth == 0 and not tail
            hit = hit or doc
            if not doc:
                text.append(quote)
                code.append(quote)
                tail += quote
            state, i = (quote, esc, doc), i + len(quote)
            continue
        if js and ch == "/" and re.search(r"(?:^|[(,=:\[!&|?{};]|=>|(?<!\w)return)$", tail[-7:]):
            j = i + 1
            while j < n and line[j] != "/":
                j += 2 if line[j] == "\\" else 1
            text.append(line[i:j + 1])
            code.append("//")
            tail, i = tail + "//", j + 1
            continue
        depth = depth + 1 if ch in "([{" else max(0, depth - 1) if ch in ")]}" else depth
        text.append(ch)
        code.append(ch)
        tail += "" if ch.isspace() else ch
        i += 1
    return "".join(text), "".join(code), state, depth, hit


def logical(src):
    """Логические строки GDScript и Python: (первая, последняя, отступ, код одной строкой)."""
    result, start = [], None
    for i, code in enumerate(src.code):
        if start is None and not src.sig[i]:
            continue
        start = i if start is None else start
        if src.depth[i + 1] == 0 and not src.cont[i + 1] and not code.rstrip().endswith("\\"):
            raw = src.raw[start]
            indent = len(raw[:len(raw) - len(raw.lstrip())].expandtabs(4))
            result.append((start, i, indent, " ".join(c.strip() for c in src.code[start:i + 1])))
            start = None
    return result


def new_scope(kind, name, start, owner, header=""):
    return {"kind": kind, "name": name, "start": start, "end": start, "owner": owner, "header": header,
            "fields": set(), "methods": 0, "decl": [start]}


def qual(scope):
    """Имя с именами владельцев до безымянного: Outer.Inner.run."""
    outer = qual(scope["owner"]) if scope and scope["name"] else ""
    return (outer + "." if outer else "") + scope["name"] if scope and scope["name"] else ""


def close(src, scope):
    if scope["kind"] == "func":
        body = src.body(scope["start"] + 1, scope["end"]) or src.body(scope["start"], scope["start"])
        size = sum(src.sig[scope["start"]:scope["end"] + 1])
        public = not scope["name"].startswith(("_", "#")) and (src.lang != "cs" or "public" in scope["header"])
        src.funcs.append({"name": scope["name"], "qual": qual(scope), "start": scope["start"],
                          "end": scope["end"], "size": size, "body": len(body), "public": public, "lines": body,
                          "print": digest(scope["name"] + "\n" + "\n".join(body))})
    elif scope["kind"] == "class":
        if src.lang in ("py", "js"):
            rx = r"\bself\.(\w+)\s*(?::[^=]*)?=(?!=)" if src.lang == "py" else r"\bthis\.(#?\w+)\s*=(?!=)"
            for i in range(scope["start"], scope["end"] + 1):
                scope["fields"].update(re.findall(rx, src.code[i]))
        src.classes.append({"name": scope["name"] or os.path.basename(src.path), "start": scope["start"],
                            "end": scope["end"], "fields": len(scope["fields"]), "methods": scope["methods"],
                            "decl": scope["decl"]})


def scopes_indent(src):
    """Функции и классы GDScript и Python по отступам."""
    top = dict(new_scope("class" if src.lang == "gd" else "module", "", 0, None), end=max(0, len(src.raw) - 1))
    stack = []
    for start, end, indent, code in logical(src):
        while stack and indent <= stack[-1][0]:
            close(src, stack.pop()[1])
        for _, scope in stack:
            scope["end"] = end
        owner = stack[-1][1] if stack else top
        head = HEAD.match(code)
        if head:
            kind = "class" if head.group(3) else "func"
            scope = new_scope(kind, head.group(4), start, owner)
            stack.append((indent, scope))
            if kind == "func" and owner["kind"] == "class":
                owner["decl"].append(start)
                owner["methods"] += not head.group(4).startswith("_")
        elif owner["kind"] == "class" and (GD_VAR.match(code) if src.lang == "gd" else re.match(r"\w+\s*[:=]", code)):
            owner["fields"].add(start)
            owner["decl"].append(start)
    while stack:
        close(src, stack.pop()[1])
    if src.lang == "gd":
        close(src, top)


def func_name(header):
    """Имя функции по заголовку перед «{» (C#, JS, TS); None — не объявление функции."""
    h = header.strip()
    if h.endswith("=>"):
        arrow = re.search(r"((?:[^\W\d]|\$)[\w$]*)\s*[:=]\s*(?:async\s*)?(?:\([^()]*\)|(?:[^\W\d]|\$)[\w$]*)\s*"
                          r"(?::[^=]*)?=>$", h)
        return arrow.group(1) if arrow else None
    h = re.sub(r"\s*:\s*(?:base|this)\s*\(.*\)$", "", h)
    h = re.sub(r"\)\s*(?::\s*[\w<>\[\]|.,?\s]+|where\s.*)$", ")", h)
    if not h.endswith(")"):
        return None
    depth, k = 0, len(h) - 1
    while k >= 0:
        depth += {")": 1, "(": -1}.get(h[k], 0)
        if depth == 0:
            break
        k -= 1
    before = re.sub(r"\s*<[^<>]*>$", "", h[:max(k, 0)].rstrip())
    found = re.search(r"((?:[^\W\d]|\$)[\w$]*)$", before)
    if k < 0 or not found:
        return None
    name, prev = found.group(1), before[:found.start()].rstrip()
    if name == "function":
        named = re.search(r"((?:[^\W\d]|\$)[\w$]*)\s*[:=]\s*(?:async\s+)?$", prev)
        return named.group(1) if named else None
    if name in CTRL or re.search(r"(?:\bnew|[.=(,!&|?])$", prev):
        return None
    return name


def scopes_brace(src):
    """Функции и классы C#, JS, TS по фигурным скобкам."""
    stack, head, head_line, paren, lit = [], [], None, 0, 0
    for ln, code in enumerate(src.code):
        if src.lang == "cs" and code.lstrip().startswith("#"):
            continue
        for part in re.split(r"([{};])", code) + [" "]:
            header = "".join(head).strip()
            # внутри скобок заголовка «{…}» и «;» — литерал или for(;;), кроме тела «=> {» и «) {»
            inner = paren > 0 and not (part == "{" and header.endswith(("=>", ")"))) or part == "}" and lit > 0
            if part not in ("{", "}", ";") or inner:
                head_line = ln if head_line is None and part.strip() else head_line
                head.append(part)
                paren = max(0, paren + part.count("(") - part.count(")"))
                lit += (part == "{") - (part == "}") if inner else 0
                continue
            start, owner = ln if head_line is None else head_line, stack[-1] if stack else None
            if part == "{":
                stack.append(brace_scope(header, start, owner, src.lang))
                stack[-1]["outer"], paren, lit = (paren, lit), 0, 0
            elif part == "}" and stack:
                scope = stack.pop()
                scope["end"], (paren, lit) = ln, scope["outer"]
                close(src, scope)
            elif part == ";" and owner and owner["kind"] == "class" and header:
                owner["decl"].append(start)
                if re.match(r"[^=(]*\w\s*(?:<[^>]*>)?\s*\(", header):
                    owner["methods"] += src.lang == "cs" and "public" in header.split("(")[0]
                elif not re.search(r"\b(?:const|static)\b", header):
                    owner["fields"].add(start)
            head, head_line = [], None


def brace_scope(header, start, owner, lang):
    classy = CLASSY.search(header)
    if classy and classy.group(1) != "enum" and "(" not in header[:classy.start()]:
        return new_scope("class" if classy.group(1) != "namespace" else "ns", classy.group(2)
                         if classy.group(1) != "namespace" else "", start, owner, header)
    name = func_name(header)
    in_class = owner is not None and owner["kind"] == "class"
    if name:
        if in_class:
            owner["decl"].append(start)
            owner["methods"] += not name.startswith(("_", "#")) and (lang != "cs" or "public" in header)
        return new_scope("func", name, start, owner, header)
    if in_class and header and "(" not in header and "=" not in header:
        owner["fields"].add(start)
        owner["decl"].append(start)
    return new_scope("block", "", start, owner, header)


def split_lines(text):
    lines = text.lstrip("\ufeff").replace("\r\n", "\n").split("\n")
    return lines[:-1] if lines and lines[-1] == "" else lines


def read_lines(path):
    try:
        with open(path, encoding="utf-8-sig", errors="replace") as handle:
            return split_lines(handle.read()) if os.path.getsize(path) <= 2_000_000 else None
    except OSError:
        return None


def generated(path, raw):
    """Сжатое или сгенерированное — только имена: *.min.*, метка в комментарии в начале, средняя строка > 300;
    причина или пусто. Одна длинная строка (картинка base64, список проверок) файл из замера не выводит.
    """
    long = [len(line) for line in raw if line.strip()]
    return "*.min.*" if ".min." in path.lower() else "средняя строка длиннее 300" if long and sum(
        long) / len(long) > 300 else next((f"метка «{line.strip()[:60]}»" for line in raw[:5] if GENERATED.search(
            line) and re.match(r"\s*(?:#|//|/?\*|<!--|;)", line)), "")


class Model:
    """Все файлы проекта: разобранный код и счёт имён по всему тексту.

    committed — как в HEAD (база снимается с принятого): правленое — из HEAD, неотслеживаемое — мимо.
    keep — файлы из базы: мерить всегда. Чужие черновики (неотслеживаемые _scratch*) — мимо, счётом foreign.
    """

    def __init__(self, root, exclude, committed=False, keep=()):
        self.root, self.sources, self.paths, self.ids, self.test_ids, self.skipped = root, {}, [], Counter(), Counter(), {}
        others = set("" if committed else (git(root, "ls-files", "-z", "--others", "--exclude-standard") or "").split("\0"))
        foreign = {p for p in others if re.match(r"_?scratch", os.path.basename(p), re.I)}
        listed, self.foreign = (git(root, "ls-files", "-z", check=True) or "").split("\0") + sorted(others - foreign), \
            sum(os.path.splitext(p)[1].lower() in LANGS for p in foreign)
        dirty = set((git(root, "diff", "--name-only", "-z", "--relative", "HEAD") or "").split("\0")) if committed else ()
        for path in sorted(set(p for p in listed if p)):
            parts, ext = path.split("/"), os.path.splitext(path)[1].lower()
            if any(p in SKIP_DIRS or p.startswith(".") for p in parts[:-1]) or parts[0] in SKIP_TOP and len(parts) > 1 \
                    or path in OWN_TOOLS or any(fnmatch.fnmatch(path, e) or path.startswith(e.rstrip("/") + "/")
                                                for e in exclude):
                continue
            self.paths.append(path)
            if ext not in LANGS and ext not in NAMES_ONLY:
                continue
            raw = split_lines(shown(root, "HEAD", path) or "") if path in dirty else read_lines(os.path.join(root, path))
            if not raw:
                continue
            ids = Counter(IDENT.findall("\n".join(raw)))
            self.ids.update(ids)
            if is_check(path):
                self.test_ids.update(ids)
            why = ext in LANGS and path not in keep and generated(path, raw)
            if ext in LANGS and not why:
                self.sources[path] = Source(path, raw, LANGS[ext])
            elif why:
                self.skipped[path] = why
        self.godot = "\n".join(read_lines(os.path.join(root, "project.godot")) or [])

    def code(self):
        return [(p, s) for p, s in self.sources.items() if s.lang != "shader"]


