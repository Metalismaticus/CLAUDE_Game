    seqs, dups = windows(model, lim["repeat_lines"])
    since = diff or stamp and "repeats" in base and changes(model.root, stamp, model)  # без --changed — с коммита базы
    joined = joined_repeats(seqs, dups, since, lim["repeat_lines"]) if since else set()
    check_repeats(base, lim, diff, rep, seqs, dups, joined)
    check_helpers(base, new, rep, helpers(model, lim))
