def hot_files(root, window):
    """Сколько из последних пунктов правили каждый файл — под нынешним именем; и сколько пунктов нашлось.

    Пункт — «Пункт|Item N:» своей партии, а не коммит (у [вид] их 3–6): номера в каждой партии свои, граница — коммит
    приёмки («Приёмка:», «Accept:», старые «Принять …») по журналу от новых к старым. Уборки («для игрока без
    изменений») не в счёт: их число уборка снизить не может, а она сама — правка файла.
    """
    log = git(root, "log", "-n", "400", "-M", "--format=%x01%s", "--name-status", "--", ".") or ""
    prefix = (git(root, "rev-parse", "--show-prefix") or "").strip()
    items, taken, alias, batch = defaultdict(set), set(), {}, 0
    for block in log.split("\x01")[1:]:
        lines = block.split("\n")
        rows = [row.split("\t") for row in lines[1:] if "\t" in row]
        alias.update({row[1]: alias.get(row[2], row[2]) for row in rows if row[0][:1] == "R" and len(row) == 3})
        batch += bool(re.match(r"(?:Accept|Приёмка|Принять)\b", lines[0]))
        item = re.match(r"(?:Пункт|Item) (\d+):", lines[0])
        key = (batch, item.group(1)) if item else None
        if item and (len(taken) < window or key in taken) and not re.search(
                r"no change for players|для игрока без изменений", lines[0]):
            taken.add(key)
            for r in (r for r in rows if r[-1].startswith(prefix)):
                items[alias.get(r[-1], r[-1])[len(prefix):]].add(key)
    return Counter({path: len(keys) for path, keys in items.items()}), len(taken)


def diff_path(text):
    """Путь из заголовка diff: без хвостового TAB (путь с пробелом), кавычек git (\\" и \\\\) и «a/» / «b/»."""
    text = re.sub(r"\\(.)", r"\1", text.rstrip("\t")[1:-1]) if text[:1] == '"' else text.rstrip("\t")  # quotepath=off
    return text[2:] if text[:2] in ("a/", "b/") else None


def shape(line, renamed=frozenset()):
    """Строка без чисел, текста в кавычках, приставок tree. и self. и имён, которые diff переименовал (renamed): правка
    только литералов или механическая правка переноса (_far → far, process_frame → tree.process_frame) её не меняет."""
    text = re.sub(r"\b(?:self|tree|get_tree\(\))\.", "", norm(line))
    text = IDENT.sub(lambda m: "0" if m.group(0) in renamed else m.group(0), text) if renamed else text
    return re.sub(r"\"[^\"]*\"|'[^']*'|(?<![\w.])\d[\d.]*", "0", text)


def changes(root, rev, model, to=None):
    """Новые значимые строки по файлам (с 0) без переносов, имена функций и методов с удалённых строк (dropped),
    перенесённые строки (добавленные, которые этот же diff удалил в другом месте), места удалений (строка, перед
    которой) и новые строки, у которых правлены только числа и текст или механически — имена, которые есть только
    по одну сторону diff, и приставка tree. (tuned: удалённая строка того же вида); to — до коммита.
    """
    diff = git(root, "diff", "-U0", "--no-color", "--no-ext-diff", "--src-prefix=a/", "--dst-prefix=b/",
               "--relative", rev, *[to] * bool(to), "--", ".") or ""
    added, removed, dropped, cuts, gone = defaultdict(list), Counter(), set(), defaultdict(set), []
    old = path = None
    left = right = right_at = 0
    for line in diff.split("\n"):
        if left and line.startswith("-"):
            if os.path.splitext(old or "")[1].lower() in LANGS:  # перенос — только из кода
                removed[norm(line[1:])] += 1
                gone.append(line[1:])
                dropped.update(n for pair in CALLABLE.findall(line[1:]) for n in pair if n)
            left -= 1
        elif right and line.startswith("+"):
            added[path].append((right_at, line[1:]))
            right_at, right = right_at + 1, right - 1
        elif line.startswith("--- "):
            old = diff_path(line[4:])
        elif line.startswith("+++ "):
            path = diff_path(line[4:])
        elif line.startswith("@@"):
            hunk = re.match(r"@@ -\d+(?:,(\d+))? \+(\d+)(?:,(\d+))?", line)
            left, right_at, right = int(hunk.group(1) or 1), int(hunk.group(2)) - 1, int(hunk.group(3) or 1)
            cuts[path].update([right_at + 1] if not right else [])
    untracked = (git(root, "ls-files", "-z", "--others", "--exclude-standard") or "").split("\0") if not to else []
    added.update({p: list(enumerate(model.sources[p].raw)) for p in untracked if p in model.sources})
    renamed = set(IDENT.findall("\n".join(gone))) ^ set(IDENT.findall("\n".join(l for v in added.values() for _, l in v)))
    new, shifted, tuned, shapes = {}, defaultdict(set), defaultdict(set), Counter(shape(line, renamed) for line in gone)
    for path, lines in added.items():
        src = model.sources.get(path)
        for index, line in (lines if src else []):
            if index < len(src.sig) and src.sig[index]:
                form = shape(line, renamed)
                moved, alike = removed[norm(line)] > 0, shapes[form] > 0
                removed[norm(line)] -= moved
                shapes[form] -= alike
                (shifted[path] if moved else new.setdefault(path, set())).add(index)
                tuned[path].update([index] if alike and not moved else [])
    return new, dropped, shifted, cuts, tuned


class Report:
    def __init__(self, diff, hot):
        self.findings, self.notes, self.diff, self.hot, self.over, self.excess = [], [], diff, hot, 0, 0

    def add(self, finding, weight, path, line, what, fix, over=False):
        """Строка находки или заметки; over — старое сверх порога находки (в --summary — «место»).

        Порядок — вес, затем файл и номер строки числом (не текстом: :105 после :1005 не встаёт).
        """
        where = path if line is None else f"{path}:{line + 1}"
        text = f"уборка: {where} — {what} — {fix}" + (" — этот diff" if finding and self.diff else "")
        (self.findings if finding else self.notes).append(((-weight * (1 + self.hot.get(path, 0)), path,
                                                            -1 if line is None else line), text))
        self.over += over


def number(value):
    return value[0] if isinstance(value, list) else value


def touched(new, path, start, end):
    return sum(1 for i in new.get(path, ()) if start <= i <= end)


def known_paths(base):
    """Файлы из базы (размер, функции, счётчики) — их мерят всегда."""
    return {k.split("::", 1)[0] for sec in ("files", "functions") + COUNTERS for k in (base or {}).get(sec, {})}


def base_stamp(root, base_path):
    """(коммит, где база менялась последний раз, путь базы от папки проекта); база вне проекта — ("", None)."""
    top, path = os.path.join(os.path.abspath(root), ""), os.path.abspath(base_path)  # relpath падает меж дисков
    rel = path[len(top):].replace("\\", "/") if os.path.normcase(path).startswith(os.path.normcase(top)) else None
    return ((git(root, "log", "-1", "--format=%H", "--", rel) or "").strip(), rel) if rel else ("", None)


def renames(model, base, stamp, rev):
    """Файлы базы, которых нет на месте: {новый путь: старый} — переименование или перенос в папку.

    Старый текст — из rev, коммита базы или HEAD; новый путь — файл вне базы, общих строк с которым не
    меньше половины большего из двух.
    """
    keyed = known_paths(base)
    gone = sorted(k for k in keyed if k not in model.sources)
    fresh, found = {p: {norm(x) for x in s.raw if x.strip()} for p, s in model.code() if gone and p not in keyed}, {}
    for old in gone:
        text = next((t for t in (shown(model.root, r, old) for r in (rev, stamp, "HEAD") if r) if t is not None), "")
        lines = {norm(x) for x in split_lines(text) if x.strip()}
        share, path = max(((len(lines & seen) / max(len(lines), len(seen)), p) for p, seen in fresh.items() if lines
                           and p not in found and os.path.splitext(p)[1] == os.path.splitext(old)[1]), default=(0, None))
        found.update({path: old} if share >= 0.5 else {})
    return found


def func_base(model, base, moved, revs):
    """Ключ базы каждой функции: запись с тем же отпечатком, если под своим ключом тело не то (перенос; новая
    одноимённая выше сдвинула «#2»), иначе своя, иначе ушедшая — того же имени в переименованном файле (сколько бы
    run() ни ушло разом); единственная неразобранная того же имени, тело которой (из первого коммита revs, где она
    есть) совпадает с нынешним хоть наполовину — перенос с правкой вызовов, и из удалённого файла. Новая run() с
    другим телом вместо удалённой — новая.
    """
    known, olds, result = base.get("functions", {}), {}, {}
    funcs = {f"{p}::{f['qual']}": f for p, s in model.code() for f in s.funcs}
    prints = {v[1]: k for k, v in known.items() if k not in funcs or funcs[k]["print"] != v[1]}
    for key, func in funcs.items():
        old = prints.get(func["print"])
        if old and old not in result.values() and known.get(key, (0, ""))[1] != func["print"]:
            result[key] = old
    result.update({k: k for k in funcs if k in known and k not in result and k not in result.values()})

    def alike(key, old):
        path, name = old.split("::", 1)
        for rev in (r for r in revs if r):
            if (rev, path) not in olds:
                text, lang = shown(model.root, rev, path), LANGS.get(os.path.splitext(path)[1].lower())
                olds[rev, path] = Source(path, split_lines(text), lang).funcs if text and lang else []
            was, now = next((f["lines"] for f in olds[rev, path] if f["qual"] == name), None), funcs[key]["lines"]
            if was is not None:
                return sum((Counter(was) & Counter(now)).values()) * 2 >= max(len(was), len(now))
        return False

    for stage in (1, 2):
        free = [k for k in known if k not in result.values()]
        names = Counter(k.split("::", 1)[1] for k in free)
        for key in [k for k in funcs if k not in result]:
            path, name = key.split("::", 1)
            old = f"{moved.get(path)}::{name}" if stage == 1 else \
                next((k for k in free if names[name] == 1 and k.endswith("::" + name) and alike(key, k)), None)
            result.update({key: old} if old in free and old not in result.values() else {})
    return result


SIZE_FIX = {"file": ("новое — своим файлом, здесь только вызов", "разнести на части — каждая меньше порога",
                     "разнести по частям перед пунктом, который его правит",
                     "перенесённое — отдельными файлами, каждый меньше порога"),
            "func": ("вынести шаг в функцию с именем",) * 3 + ("перенесённое — своей функцией, здесь только вызов",)}


def check_sizes(model, base, lim, diff, rep, moved, revs):
    """Н1 и Н2 — файлы и функции длиннее порога; заметки о больших файлах и функциях.

    С --changed судится выросшее против rev — новыми строками или перенесёнными (перенос в большой файл, помощник,
    влитый в длинную функцию); функции, которой в этом файле на rev не было, в рост идут только новые строки.
    Потолок — от меньшего из базы и размера на rev: место, освобождённое уборкой в партии, следующим пунктам не
    достаётся. Сверх потолка только вызов нового (call_lines новых строк, без перенесённых) — заметка, не находка;
    перерос перенесённым — «перенесённое — отдельно»; без --changed, какое новое, не видно — «разнести по частям».
    excess — строк сверх порога (--summary): у файла сверх порога — только его, излишек функций не прибавляется.
    revs — (rev, коммит базы, HEAD): где искать тело ушедшей функции (func_base).
    """
    files, funcs, rev, new = base.get("files", {}), base.get("functions", {}), revs[0], diff and diff[0]
    keys = func_base(model, base, moved, revs)

    def judge(kind, path, line, what, size, was, fresh, growth):
        """Сверх потолка — находка (только вызов нового — заметка); большое — заметка (с --changed — если выросло)."""
        top, note, fix = lim[kind + "_lines"], lim[f"note_{kind}_lines"], SIZE_FIX[kind]
        cap, carried = max(top, was + lim[kind + "_growth"] if was else 0), max(0, growth - fresh)
        limit, call = f"порог {top}" + (f", база {was}, допуск +{lim[kind + '_growth']}" if was else ""), \
            bool(was) and new is not None and fresh <= lim["call_lines"] and not carried
        if size > cap:
            rep.add(not call, size / top, path, line, f"{what[0]} длиннее нормы ({size} / {limit})" + ", сверх допуска"
                    " — только вызов нового" * call, fix[3] if carried and size - carried <= cap else fix[2] if call
                    or was and new is None else fix[0] if was else fix[1])
        elif size > note and (new is None or size - fresh <= note):
            rep.add(False, size / top, path, line, f"{what[1]} ({size} / "
                    f"{limit if was else f'заметка от {note}, порог {top}'})", fix[2], over=size > top)

    for path, src in model.code():
        was, fresh = files.get(path) or files.get(moved.get(path)), len(new.get(path, ())) if new else 0
        rep.excess += (max(0, src.size - lim["file_lines"]) or sum(max(0, f["size"] - lim["func_lines"])
                                                                   for f in src.funcs)) if new is None else 0
        changed = new is not None and any(path in lines for lines in (new, diff[2], diff[3]))  # и только удаления:
        # влитый помощник git показывает удалением его заголовка — граница функции сдвинулась, строки на месте
        text = (shown(model.root, rev, path) or path in moved and shown(model.root, rev, moved[path])) if changed else None
        then = Source(path, split_lines(text), src.lang) if text else None
        sizes = {f["qual"]: f["size"] for f in then.funcs} if then else {}
        growth = src.size - (then.size if then else 0) if changed else 0
        if new is None or growth > 0:
            judge("file", path, None, ("файл", "файл большой"), src.size, min(was, then.size) if was and then else was,
                  fresh, growth)
        for func in src.funcs:
            added, key = touched(new, path, func["start"], func["end"]) if new else 0, keys.get(f"{path}::{func['qual']}")
            grew = func["size"] - sizes.get(func["qual"], func["size"] - added) if changed else 0
            if new is None or grew > 0:
                judge("func", path, func["start"], (f"функция {func['qual']}", f"функция {func['qual']} большая"),
                      func["size"], min(funcs[key][0], sizes.get(func["qual"], funcs[key][0])) if key else None,
                      added, grew)


def window_key(seq, k, width):
    return digest("\n".join(s for _, s in seq[k:k + width]))


def windows(model, width):
    """Окна из width значимых строк: последовательности по файлам и повторы (хеш → места).

    Мимо — подключения: import, using, extends, `const X := preload(…)`, строки многострочного `import {…} from`.
    """
    seqs, places = {}, defaultdict(list)
    for path, src in model.sources.items():
        seq, block = [], False
        for i in (i for i in range(len(src.raw)) if src.sig[i]):
            s = norm(src.text[i])
            opens = not block and re.match(r"(?:import|export)(?: type)? ?(?:[\w$]+, ?)?\{[^}]*$", s)
            if block or opens:
                block = bool(opens) or "}" not in s
            elif re.search(r"\w", s) and not re.match(r"(?:(?:import|from|using|extends|class_name)\b|#include\b|export "
                                                      r"\{|(?:const|var) \w+ ?:?= ?(?:pre)?load\()", s):
                seq.append((i, s))
        seqs[path] = seq
        for k in range(len(seq) - width + 1):
            key = window_key(seq, k, width)
            last = places[key][-1] if places[key] else None
            if not (last and last[0] == path and k - last[1] < width):
                places[key].append((path, k))
    return seqs, {key: spots for key, spots in places.items() if len(spots) > 1}


def runs(pairs):
    """Цепочки соседних совпавших окон пары мест: (a, i, b, j, окон) — повтор целиком."""
    for a, i, b, j in sorted(pairs):
        if (a, i - 1, b, j - 1) not in pairs:
            run = 1
            while (a, i + run, b, j + run) in pairs:
                run += 1
            yield a, i, b, j, run


def carried(seqs, diff, spots, size):
    """Места повтора по size строк: True — перенос, а не новая копия: ни в одном месте нового (diff — changes()) не
    больше перенесённого, и хоть одно место diff задел — перенос с правкой (root → tree.root) или удаление между
    строками (соседние куски сошлись после уборки); False — новая копия; None — diff их не задел.
    """
    new, _, shifted, cuts = diff[:4]
    touched = False
    for path, k in spots:
        rows = [seqs[path][j][0] for j in range(k, k + size)]
        fresh, kept = (sum(i in lines.get(path, ()) for i in rows) for lines in (new, shifted))
        if fresh > kept:
            return False
        touched = touched or kept or any(rows[0] < cut <= rows[-1] for cut in cuts.get(path, ()))
    return True if touched else None


def joined_repeats(seqs, dups, diff, width):
    """Ключи повторов из базы, задетых переносом, — одно правило для --changed, --tighten и Н10 (подъём базы).

    Судится повтор целиком — цепочка окон пары мест (carried по всем её строкам), а не окно: иначе окна одного
    куска, перенесённого с правкой, расходились бы. Ключ — по всем своим парам: новой копии нет ни в одной, хоть
    одна задета. Копия, пережившая прошлый /done, не задета — так и остаётся находкой.
    """
    verdicts = defaultdict(set)
    for a, i, b, j, run in runs({spots[0] + other for spots in dups.values() for other in spots[1:]}):
        verdict = carried(seqs, diff, [(a, i), (b, j)], run + width - 1)
        for r in range(run):
            verdicts[window_key(seqs[a], i + r, width)].add(verdict)
    return {key for key, seen in verdicts.items() if True in seen and False not in seen}


def check_repeats(base, lim, diff, rep, seqs, dups, joined):
    """Н3 — повтор блока: с --changed — хоть одна сторона новая; без — мест больше, чем в базе.

    Повтор из базы, задетый переносом (joined: с --changed — этим diff, без — с коммита базы), и соседние куски,
    сошедшиеся после уборки, — заметка; --tighten вносит их в базу.
    """
    width, known, new = lim["repeat_lines"], base.get("repeats", {}), diff and diff[0]

    def fresh(path, k):
        return new is not None and any(seqs[path][j][0] in new.get(path, ()) for j in range(k, k + width))

    pairs = set()
    for key, spots in dups.items():
        if len(spots) > known.get(key, 0) if new is None else any(fresh(p, k) for p, k in spots):
            pairs.update(spots[0] + other for other in spots[1:])
    for a, i, b, j, run in runs(pairs):
        if fresh(a, i) and not fresh(b, j):
            a, i, b, j = b, j, a, i
        size, origin, other = run + width - 1, f"{a}:{seqs[a][i][0] + 1}", f"{b}:{seqs[b][j][0] + 1}"
        old = all(window_key(seqs[a], i + r, width) in joined for r in range(run))
        if new is None:  # какая сторона новая, не знаем — обе поимённо
            rep.add(not old, size / width, a, seqs[a][i][0], f"повтор {size} строк: здесь и в {other}" + " — из базы, "
                    "задет переносом" * old + f" ({size} / порог {width})", "оставить одно место, во втором — вызов")
        else:
            rep.add(not old, size / width, b, seqs[b][j][0], f"повтор {size} строк с {origin}" + " — из базы, задет"
                    " переносом" * old + f" ({size} / порог {width})", f"вызвать {origin}")


def helpers(model, lim):
    """Одноимённые функции с тем же телом в разных файлах: «имя:отпечаток» → [(файл, функция)]."""
    groups = defaultdict(list)
    for path, src in model.code():
        for func in src.funcs:
            if func["body"] >= lim["helper_lines"]:
                groups[f"{func['name']}:{func['print']}"].append((path, func))
    return {key: items for key, items in groups.items() if len(set(p for p, _ in items)) > 1}


def check_helpers(base, new, rep, groups):
    """Н4 — одноимённый помощник с тем же телом в двух файлах; с --changed — задетый этим diff, но у копии из базы,
    где правлен только заголовок (export, static), — заметка: файлов не прибавилось."""
    known = base.get("helpers", {})
    for key, items in groups.items():
        files = len(set(p for p, _ in items))
        fresh = [(p, f) for p, f in items if new is not None and touched(new, p, f["start"], f["end"])]
        if (files > known.get(key, 0)) if new is None else fresh:
            path, func = (fresh or items)[-1]
            other = next(p for p, _ in items if p != path)
            old = new is not None and files <= known.get(key, 0) and not any(
                touched(new, p, f["start"] + 1, f["end"]) for p, f in fresh)
            rep.add(not old, files, path, func["start"], f"помощник {func['name']} — то же тело, что в {other}"
                    + " — из базы, задет заголовок" * old + f" (файлов {files} / порог 1)",
                    "вынести в общий файл, в обоих местах — вызов")


def split_params(code, pos):
    """Параметры от открывающей скобки до парной и остаток строки после неё."""
    depth, cuts = 1, [pos - 1]
    for k in range(pos, len(code)):
        depth += (code[k] in "([{") - (code[k] in ")]}")
        if depth == 0 or code[k] == "," and depth == 1:
            cuts.append(k)
        if depth == 0:
            return [p for p in (code[a + 1:b].strip() for a, b in zip(cuts, cuts[1:])) if p], code[k + 1:]
    return [], ""


def declared(code):
    """Имена, объявленные в логической строке GDScript (var, const, параметры func): [(имя, тип)] — тип True или
    False, у `:= Класс.ИМЯ` — (Класс, ИМЯ): тип того объявления."""
    found = [(m.group(1), m.group(2)) for m in re.finditer(r"\b(?:var|const)\s+(\w+)(.*)", code)]
    for func in re.finditer(r"\bfunc\b\s*\w*\s*\(", code):
        found += [m.groups() for m in (re.match(r"(\w+)(.*)", p) for p in split_params(code, func.end())[0]) if m]
    aliases = [re.match(r"[ \t]*:=[ \t]*([A-Z]\w*)\.(\w+)[ \t]*$", rest) for _, rest in found]
    return [(name, alias.groups() if alias else bool(DECL_TYPED.match(rest))) for (name, rest), alias in zip(found, aliases)]


def untyped(src, typed_calls, typed_of):
    """Н5: объявления GDScript без типа — var, параметр, возврат func, переменная цикла.

    Цикл по имени — по его объявлению: ближнему выше в той же функции, иначе вне функций этого файла или его предков
    по extends (typed_of). Прочие файлы счёт не меняют: удалённый где-то псевдоним или параметр того же имени не
    отнимают тип; функция, перенесённая целиком к тем же предкам, — тоже.
    """
    marks, lines, decl, home = [], logical(src), defaultdict(list), {}
    for func in sorted(src.funcs, key=lambda f: f["start"]):  # строка → начало своей функции
        home.update(dict.fromkeys(range(func["start"], func["end"] + 1), func["start"]))
    for start, _, _, code in lines:
        for name, typed in declared(code) if home.get(start) is not None else ():
            decl[name].append((start, typed))

    def typed_name(name, line):
        scope = home.get(line)
        near = [t for at, t in decl.get(name, ()) if at <= line and scope is not None and home.get(at) == scope]
        return typed_of(src.path, name, near[-1] if near else None)

    for start, _, _, code in lines:
        var = GD_VAR.match(code)
        if var and var.group(2) in (None, "="):
            marks.append((start, f"var {var.group(1)}"))
        for func in re.finditer(r"\bfunc\b\s*(\w*)\s*\(", code):
            params, rest = split_params(code, func.end())
            marks += [(start, f"параметр {p.split('=')[0].strip()}") for p in params
                      if not p.startswith("...") and not re.match(r"\w+\s*:", p)]
            if not re.match(r"\s*->", rest):
                marks.append((start, f"возврат {func.group(1) or 'лямбды'}"))
        loop = re.match(r"\s*for\s+(\w+)\s+in\s+(.+?)\s*:(?:\s|$)", code)
        it = loop.group(2) if loop else ""
        call = re.search(r"(\w+)\([^()]*\)$", it)
        if loop and not (INT_LOOP.search(it) or re.fullmatch(r"\w+", it) and typed_name(it, start)
                         or call and call.group(1) in typed_calls):
            marks.append((start, f"for {loop.group(1)}"))
    return marks


def private_access(src):
    """Н6: проверка обращается к закрытому — obj._имя, .call("_…"), .get(&"_…")."""
    marks = []
    for i, code in enumerate(src.code):
        for hit in re.finditer(r"\._[A-Za-z]\w*", code):
            before = code[:hit.start()].rstrip()
            if not re.search(r"\b(?:self|super|this|cls)$|super\(\)$", before) and re.search(r"[\w)\]]$", before):
                marks.append((i, hit.group(0)))
        if PRIVATE_CALL.search(src.text[i]):
            marks.append((i, PRIVATE_CALL.search(src.text[i]).group(0)))
    return marks


def counters(model):
    """Места Н5–Н7 по видам и файлам: {вид: {файл: [(строка, что)]}}."""
    found = {kind: {} for kind in ("untyped", "private", "byname")}
    names, members, parents, classes, loads = set(), defaultdict(dict), {}, {}, defaultdict(dict)
    engine = typed_by_engine(model)
    for path, src in model.sources.items():
        if src.lang == "gd":
            names.update(re.findall(r"\bfunc\s+(\w+)", "\n".join(src.code)))
            inside = {i for f in src.funcs for i in range(f["start"], f["end"] + 1)}
            for start, _, indent, code in [] if engine else logical(src):  # вне функций: объявления, предок,
                if start in inside:                                          # class_name, const X := preload(…)
                    continue
                members[path].update(declared(code))
                text = "" if indent else src.text[start]
                head = re.match(r"\s*(?:class_name\s+(\w+)\s*)?(?:extends\s+(?:(\w+)|[\"']res://([^\"']+)))?", text)
                load = re.match(r"\s*const\s+(\w+)\s*:?=\s*preload\(\s*[\"']res://([^\"']+)[\"']", text)
                classes.update({head.group(1): path} if head.group(1) else {})
                parents.update({path: head.group(2) or head.group(3)} if head.group(2) or head.group(3) else {})
                loads[path].update([load.groups()] if load else [])
        elif src.lang == "cs":
            names.update(re.findall(r"\bpublic\b[^;{}=()]*?\b(\w+)\s*(?:<[^<>()]*>)?\s*\(", "\n".join(src.code)))
    typed_calls = TYPED_CALLS | set(re.findall(TYPED_RETURN, "\n".join(
        "\n".join(s.code) for s in model.sources.values() if s.lang == "gd")))

    def typed_of(path, name, value=None, seen=()):
        """Тип имени: value — объявление в функции, иначе вне функций файла path и его предков (extends); `:= Класс.ИМЯ`
        — как у ИМЯ в файле класса (class_name или `const Класс := preload(…)` рядом; класс не проекта, Vector3.UP,
        — с типом); не нашлось — без типа."""
        home = path
        while value is None and path in members and path not in seen:
            seen += (path,)
            home, value, path = path, members[path].get(name), classes.get(parents.get(path), parents.get(path))
        if isinstance(value, tuple):
            owner = loads[home].get(value[0]) or classes.get(value[0])
            return owner is None or typed_of(owner, value[1], None, seen)
        return bool(value)

    for path, src in model.code():
        if src.lang == "gd" and not engine:
            found["untyped"][path] = untyped(src, typed_calls, typed_of)
        if is_test(path) and src.lang != "py":  # в Python sys._getframe, os._exit — не чужое закрытое
            found["private"][path] = private_access(src)
        if src.lang in ("gd", "cs"):
            found["byname"][path] = [(i, m.group(1)) for i, text in enumerate(src.text)
                                     for m in BYNAME.finditer(text) if m.group(1) not in names]
    return {kind: {p: marks for p, marks in per_file.items() if marks} for kind, per_file in found.items()}, names


COUNTER_TEXT = {"untyped": ("объявлений без типа", "дописать тип"), "byname": ("вызов по имени, которого нет", ""),
                "private": ("проверка лезет в закрытое", "открытый метод или ввод")}


def check_counters(model, base, diff, rep, found, names, moved):
    """Н5–Н7 — сверх итога базы (перенос между файлами не в счёт); с --changed ещё места на новых строках и вызовы по
    имени, которое этот diff удалил.

    С --changed старые строки Н5 судятся итогом, как без флагов: тип им могла отнять правка в другом файле (у предка
    снят тип, у функции — тип возврата); Н7 — вызовы имён, чьи объявления diff удалил (переименован метод C#); Н6 от
    других файлов не зависит. Н5 и Н6 на старой строке, где правлены только числа, текст или имена переноса (tuned),
    — заметка: объявление или обращение не новое, в итоге оно старое.
    """
    new, dropped, tuned = (diff[0], diff[1], diff[4]) if diff else (None, set(), {})
    cs_names = sorted(n for n in names if n[:1].isupper())
    for kind, per_file in found.items():
        known, what, fix = base.get(kind, {}), *COUNTER_TEXT[kind]
        fresh, old = defaultdict(list), defaultdict(list)
        for path, marks in per_file.items():
            for line, name in marks:
                recent = new is not None and (line in new.get(path, ()) or kind == "byname" and name in dropped)
                if recent and kind != "byname" and line in tuned.get(path, ()):
                    rep.add(False, 0.5, path, line, f"{what}: {name} — старое "
                            f"{dict(private='обращение', untyped='объявление')[kind]}, правлены числа, текст или имена "
                            "переноса", fix)
                    recent = False
                (fresh if recent else old)[path].append((line, name))
        over = (new is None or kind == "untyped") and sum(map(len, old.values())) > sum(known.values())
        for path, marks, was, aged in [(p, v, 0, "") for p, v in fresh.items()] + [
                (p, v, known.get(p, known.get(moved.get(p), 0)), " в старых строках" * (new is not None))
                for p, v in old.items() if over]:
            if len(marks) <= was:
                continue
            if was:  # какие из мест новые, не знаем — только число
                rep.add(True, len(marks) - was, path, None, f"{what}{aged}: на {len(marks) - was} больше базы "
                        f"({len(marks)} / порог 0, база {was})", fix or "поправить имя")
            elif kind == "byname":
                for line, name in marks:
                    like = difflib.get_close_matches(name, cs_names, n=1, cutoff=0.6)
                    rep.add(True, 1, path, line, f"{what}: «{name}»",
                            f"в C# есть {like[0]}" if like else "такого метода нет ни в C#, ни в GDScript — поправить имя")
            else:
                sample = ", ".join(m[1] for m in marks[:3]) + (" …" if len(marks) > 3 else "")
                rep.add(True, len(marks), path, marks[0][0], f"{what}{aged}: {sample} ({len(marks)} / порог 0)", fix)


